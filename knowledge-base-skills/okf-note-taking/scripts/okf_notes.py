#!/usr/bin/env python3
"""Minimal CLI helper for maintaining an OKF v0.2 note bundle.

Usage:
    python okf_notes.py init [directory] --name "My Notes"
    python okf_notes.py lfs-setup [directory]
    python okf_notes.py new topics/backpropagation.md --title "Backpropagation"
    python okf_notes.py link topics/backpropagation.md --to topics/neural-networks.md
    python okf_notes.py attach topics/backpropagation.md --file gradient.png --caption "Gradient flow"
    python okf_notes.py index --regenerate
    python okf_notes.py check
    python okf_notes.py log "Created backpropagation note" --dir topics
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

try:
    import yaml

    # Keep ISO 8601 timestamps as strings so round-tripping preserves
    # the original formatting (e.g. 2026-08-26T14:00:00Z).
    def _str_timestamp(loader: yaml.SafeLoader, node: yaml.Node) -> str:
        return str(loader.construct_scalar(node))

    yaml.SafeLoader.add_constructor("tag:yaml.org,2002:timestamp", _str_timestamp)
except ImportError:  # pragma: no cover
    yaml = None  # type: ignore[assignment]


ACTOR = "kimi-code-cli"
RESERVED = {"index.md", "log.md"}

# File patterns routed through Git LFS when LFS support is enabled.
LFS_PATTERNS = [
    "assets/**/*.png",
    "assets/**/*.jpg",
    "assets/**/*.jpeg",
    "assets/**/*.gif",
    "assets/**/*.webp",
    "assets/**/*.svg",
    "assets/**/*.mp4",
    "assets/**/*.mov",
    "assets/**/*.webm",
    "assets/**/*.pdf",
    "assets/**/*.zip",
]
LFS_ATTRIBUTES_HEADER = (
    "# Auto-generated by okf_notes.py\n"
    "# Route large media files in assets/ through Git LFS.\n"
)


def now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def require_yaml() -> None:
    if yaml is None:
        print(
            "PyYAML is required for this command. Install it with:\n"
            "  pip install pyyaml\n"
            "or activate the project virtual environment.",
            file=sys.stderr,
        )
        sys.exit(1)


def is_concept(path: Path) -> bool:
    return path.suffix == ".md" and path.name not in RESERVED


def split_frontmatter(text: str) -> tuple[dict[str, Any] | None, str]:
    """Return (frontmatter_dict, body). If no frontmatter, return (None, text)."""
    require_yaml()
    if not text.startswith("---"):
        return None, text
    parts = text.split("---", 2)
    if len(parts) < 3:
        return None, text
    try:
        meta = yaml.safe_load(parts[1]) or {}
    except yaml.YAMLError:
        return None, text
    return meta, parts[2].lstrip("\n")


def build_concept(
    concept_type: str,
    title: str,
    description: str = "",
    tags: list[str] | None = None,
) -> tuple[str, dict[str, Any]]:
    tags = tags or []
    tags_yaml = "[" + ", ".join(tags) + "]" if tags else "[]"
    desc = description or title
    meta: dict[str, Any] = {
        "type": concept_type,
        "title": title,
        "description": desc,
        "tags": tags,
        "status": "draft",
        "generated": {"by": ACTOR, "at": now_iso()},
    }
    content = f"""---
type: {concept_type}
title: {title}
description: {desc}
tags: {tags_yaml}
status: draft
generated: {{ by: {ACTOR}, at: {now_iso()} }}
---

# Summary

"""
    return content, meta


def ensure_log_entry(log_path: Path, message: str, date: str | None = None) -> None:
    """Append a dated entry to a log.md file."""
    date = date or now_iso()[:10]
    header = "# Update Log\n\n"
    if log_path.exists():
        text = log_path.read_text(encoding="utf-8")
    else:
        text = header

    # Ensure header exists
    if not text.startswith("#"):
        text = header + text

    # Insert new date section at the top if not present
    date_heading = f"## {date}"
    if date_heading not in text:
        text = text.replace(header, f"{header}{date_heading}\n", 1)

    lines = text.splitlines()
    insert_idx = len(lines)
    for i, line in enumerate(lines):
        if line == date_heading:
            insert_idx = i + 1
            break

    # Find next date heading to avoid appending under wrong date
    for j in range(insert_idx, len(lines)):
        if lines[j].startswith("## ") and lines[j] != date_heading:
            insert_idx = j
            break

    lines.insert(insert_idx, f"* {message}")
    log_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def update_index(index_path: Path, title: str, rel_path: str, description: str) -> None:
    """Add or update an entry in an index.md."""
    entry = f"* [{title}]({rel_path}) - {description}\n"
    if index_path.exists():
        text = index_path.read_text(encoding="utf-8")
        # Avoid duplicate links
        if rel_path in text:
            return
    else:
        text = f"# {index_path.parent.name or 'Index'}\n\n"
    text += entry
    index_path.write_text(text, encoding="utf-8")


def relative_to_log(log_path: Path, concept_path: Path) -> str:
    """Return a path from the log file to the concept file."""
    return Path(
        concept_path.relative_to(log_path.parent.parent)
    ).as_posix()


def cmd_new(args: argparse.Namespace) -> int:
    path = Path(args.path)
    if path.exists():
        print(f"error: file already exists: {path}", file=sys.stderr)
        return 1
    path.parent.mkdir(parents=True, exist_ok=True)
    content, meta = build_concept(
        concept_type=args.type or "Note",
        title=args.title or path.stem.replace("-", " ").replace("_", " ").title(),
        description=args.description or "",
        tags=args.tags or [],
    )
    path.write_text(content, encoding="utf-8")
    print(f"created: {path}")

    # Update index
    index_path = path.parent / "index.md"
    update_index(
        index_path,
        title=meta["title"],
        rel_path=path.name,
        description=meta.get("description", ""),
    )
    print(f"updated: {index_path}")

    # Update log
    log_path = path.parent / "log.md"
    if not log_path.exists() and path.parent != Path("."):
        log_path = Path("log.md")
    ensure_log_entry(
        log_path,
        f"**Creation**: Added [{meta['title']}]({relative_to_log(log_path, path)}).",
    )
    print(f"updated: {log_path}")
    return 0


def cmd_link(args: argparse.Namespace) -> int:
    require_yaml()
    source = Path(args.from_path)
    target = Path(args.to)
    if not source.exists():
        print(f"error: source does not exist: {source}", file=sys.stderr)
        return 1

    text = source.read_text(encoding="utf-8")
    meta, body = split_frontmatter(text) or ({}, text)
    target_title = args.text or target.stem.replace("-", " ").replace("_", " ").title()

    # Try to read target title if it exists
    if target.exists():
        tmeta, _ = split_frontmatter(target.read_text(encoding="utf-8")) or ({}, "")
        target_title = tmeta.get("title") or target_title

    # Preserve original frontmatter text to avoid reformatting timestamps/tags.
    if text.startswith("---"):
        end = text.find("---", 3)
        frontmatter_text = text[: end + 3] if end != -1 else ""
    else:
        frontmatter_text = ""

    # Use a bundle-relative link when possible.
    try:
        link_path = target.relative_to(source.parent).as_posix()
    except ValueError:
        link_path = target.as_posix()
    link = f"[{target_title}]({link_path})"
    section = "# Related notes\n\n"

    if "# Related notes" in body:
        body = body.rstrip("\n") + f"\n- {link}\n"
    else:
        body = body.rstrip("\n") + "\n\n" + section + f"- {link}\n\n"

    source.write_text(frontmatter_text + "\n" + body, encoding="utf-8")
    print(f"linked: {source} -> {target}")
    return 0


def build_frontmatter(meta: dict[str, Any], flow_style: bool = True) -> str:
    """Serialize frontmatter dict to YAML block.

    Args:
        meta: Frontmatter dictionary.
        flow_style: If True, emit compact inline YAML for lists/dicts
            (e.g. tags: [a, b]). If False, emit block YAML which is more
            human-readable for nested structures.
    """
    require_yaml()
    return "---\n" + yaml.safe_dump(
        meta,
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=flow_style,
        width=float("inf"),
    ) + "---\n"


def build_concept_document(
    meta: dict[str, Any],
    body: str = "",
    flow_style: bool = True,
) -> str:
    """Build a full OKF concept document from a complete meta dict and body.

    Args:
        meta: Complete frontmatter dictionary. Must include 'type'.
        body: Markdown body to place after the frontmatter.
        flow_style: YAML style passed to build_frontmatter.

    Returns:
        The full concept document as a string.
    """
    return build_frontmatter(meta, flow_style=flow_style) + "\n" + body


def split_text_frontmatter(text: str) -> tuple[str, str] | None:
    """Return (frontmatter_block_text, body_text) without parsing YAML."""
    if not text.startswith("---"):
        return None
    end = text.find("---", 3)
    if end == -1:
        return None
    return text[: end + 3], text[end + 3 :].lstrip("\n")


def safe_filename(name: str) -> str:
    """Normalize a filename to be safe across filesystems."""
    name = name.lower().strip().replace(" ", "-")
    return re.sub(r"[^a-z0-9_.\-]", "", name)


def cmd_index(args: argparse.Namespace) -> int:
    require_yaml()
    root = Path(".")
    dirs: set[Path] = set()
    for md in root.rglob("*.md"):
        if is_concept(md):
            dirs.add(md.parent)

    for d in sorted(dirs):
        index_path = d / "index.md"
        if index_path.exists() and not args.regenerate:
            continue

        lines = [f"# {d.name or 'Index'}", ""]
        concepts = sorted(p for p in d.iterdir() if is_concept(p))
        for concept in concepts:
            meta, _ = split_frontmatter(concept.read_text(encoding="utf-8")) or ({}, "")
            title = meta.get("title") or concept.stem
            desc = meta.get("description", "")
            lines.append(f"* [{title}]({concept.name}) - {desc}".rstrip(" -"))

        subdirs = sorted(sd for sd in d.iterdir() if sd.is_dir() and any(sd.rglob("*.md")))
        if subdirs:
            lines.extend(["", "# Subdirectories"])
            for sd in subdirs:
                lines.append(f"* [{sd.name}]({sd.name}/)")

        index_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"generated: {index_path}")
    return 0


def cmd_check(args: argparse.Namespace) -> int:
    require_yaml()
    root = Path(".")
    warnings = 0
    for md in root.rglob("*.md"):
        if md.name in RESERVED:
            continue
        text = md.read_text(encoding="utf-8")
        meta, body = split_frontmatter(text)
        if meta is None:
            print(f"warn: {md} has no parseable frontmatter")
            warnings += 1
            continue
        if not meta.get("type"):
            print(f"warn: {md} frontmatter missing 'type'")
            warnings += 1

        # Check footnote ids map to sources ids
        source_ids = {s.get("id") for s in meta.get("sources", []) if isinstance(s, dict)}
        for fn in re.findall(r"\[\^([^\]\s]+)\]", body):
            if fn not in source_ids:
                print(f"warn: {md} footnote [^{fn}] has no matching sources[].id")
                warnings += 1

        # Check local image references exist
        for alt, ref in re.findall(r"!\[([^\]]*)\]\(([^)]+)\)", body):
            ref = ref.strip()
            if re.match(r"^[a-z][a-z0-9+.-]*://", ref, re.IGNORECASE):
                continue  # external URL, not checked
            if ref.startswith("/"):
                asset_path = root / ref.lstrip("/")
            else:
                asset_path = md.parent / ref
            if not asset_path.exists():
                print(f"warn: {md} image '{ref}' not found at {asset_path.resolve()}")
                warnings += 1

    if warnings:
        print(f"\n{warnings} warning(s) found. OKF consumers would still tolerate them.")
    else:
        print("OK: bundle looks conformant.")
    return 0


def cmd_log(args: argparse.Namespace) -> int:
    log_path = Path(args.dir) / "log.md" if args.dir else Path("log.md")
    log_path.parent.mkdir(parents=True, exist_ok=True)
    ensure_log_entry(log_path, args.message, args.date)
    print(f"updated: {log_path}")
    return 0


def cmd_attach(args: argparse.Namespace) -> int:
    source = Path(args.concept)
    image = Path(args.file)
    if not source.exists():
        print(f"error: concept does not exist: {source}", file=sys.stderr)
        return 1
    if not image.exists():
        print(f"error: image file does not exist: {image}", file=sys.stderr)
        return 1

    text = source.read_text(encoding="utf-8")
    split = split_text_frontmatter(text)
    if split is None:
        print(f"error: {source} has no OKF frontmatter", file=sys.stderr)
        return 1
    frontmatter_text, body = split

    # Decide asset destination: assets/<concept-dir>/<stem>/<filename>
    rel = source.relative_to(Path("."))
    asset_dir = Path("assets") / rel.with_suffix("")
    asset_dir.mkdir(parents=True, exist_ok=True)
    dest_name = safe_filename(image.name)
    dest = asset_dir / dest_name
    # Avoid overwriting by appending a counter
    counter = 1
    stem = dest.stem
    suffix = dest.suffix
    while dest.exists():
        dest = asset_dir / f"{stem}-{counter}{suffix}"
        counter += 1

    import shutil

    shutil.copy2(image, dest)

    # Path from concept file to image (relative for body)
    rel_path = Path(os.path.relpath(dest, source.parent)).as_posix()

    # Bundle-relative absolute path for frontmatter record (stable if doc moves)
    bundle_path = "/" + dest.as_posix()

    # Optionally record asset in frontmatter without reformatting the rest.
    if args.record:
        if bundle_path not in frontmatter_text:
            inner = frontmatter_text[:-3].rstrip("\n")
            if "assets:" in inner:
                lines = inner.splitlines()
                for i, line in enumerate(lines):
                    if line.strip() == "assets:":
                        lines.insert(i + 1, f"- {bundle_path}")
                        break
                inner = "\n".join(lines) + "\n"
            else:
                inner += f"\nassets:\n- {bundle_path}\n"
            frontmatter_text = inner + "---\n"

    caption = args.caption or image.stem.replace("-", " ").replace("_", " ").title()
    image_line = f"![{caption}]({rel_path})\n\n"
    if args.caption:
        image_line += f"*{caption}*\n\n"

    body = body.rstrip("\n") + "\n\n" + image_line
    source.write_text(frontmatter_text + "\n" + body, encoding="utf-8")
    print(f"attached: {dest} -> {source}")
    if args.record:
        print(f"recorded: {bundle_path} in frontmatter assets")
    return 0


def ensure_gitattributes(root: Path, patterns: list[str] | None = None) -> bool:
    """Create or update .gitattributes to route asset patterns through Git LFS.

    Returns True if the file was created or modified, False otherwise.
    """
    patterns = patterns or LFS_PATTERNS
    path = root / ".gitattributes"

    existing_lines: set[str] = set()
    if path.exists():
        existing_text = path.read_text(encoding="utf-8")
        existing_lines = set(existing_text.splitlines())
    else:
        existing_text = ""

    new_lines: list[str] = []
    for pat in patterns:
        line = f"{pat} filter=lfs diff=lfs merge=lfs -text"
        if line not in existing_lines:
            new_lines.append(line)

    if not new_lines:
        return False

    # Preserve existing content and append missing rules.
    text = existing_text
    if text and not text.endswith("\n"):
        text += "\n"
    if LFS_ATTRIBUTES_HEADER.splitlines()[0] not in existing_lines:
        text += LFS_ATTRIBUTES_HEADER
    text += "\n".join(new_lines) + "\n"
    path.write_text(text, encoding="utf-8")
    return True


def cmd_lfs_setup(args: argparse.Namespace) -> int:
    root = Path(args.directory)
    if not root.exists():
        print(f"error: directory does not exist: {root}", file=sys.stderr)
        return 1
    modified = ensure_gitattributes(root, LFS_PATTERNS)
    if modified:
        print(f"updated: {root / '.gitattributes'}")
    else:
        print(f"up-to-date: {root / '.gitattributes'}")
    return 0


def cmd_init(args: argparse.Namespace) -> int:
    root = Path(args.directory)
    root.mkdir(parents=True, exist_ok=True)
    name = args.name or root.name or "Notes"

    subdirs = ["topics", "references", "computations"]
    for sub in subdirs:
        (root / sub).mkdir(exist_ok=True)

    # Root index.md with okf_version frontmatter.
    root_index = root / "index.md"
    if not root_index.exists():
        root_index.write_text(
            f"""---
okf_version: "0.2"
---

# {name}

A learning-note bundle in the Open Knowledge Format (OKF) v0.2.

# Directories

* [topics](topics/) - thematic learning notes.
* [references](references/) - external-source mirrors and citations.
* [computations](computations/) - reproducible formulas, code, and attested computations.

# Update Log

See [log.md](log.md) for the history of changes.
""",
            encoding="utf-8",
        )
        print(f"created: {root_index}")

    # Root log.md.
    root_log = root / "log.md"
    if not root_log.exists():
        root_log.write_text(
            "# Update Log\n\n"
            f"## {now_iso()[:10]}\n"
            "* **Initialization**: Created the OKF note bundle.\n",
            encoding="utf-8",
        )
        print(f"created: {root_log}")

    # Per-subdirectory indexes.
    for sub in subdirs:
        idx = root / sub / "index.md"
        if not idx.exists():
            idx.write_text(
                f"# {sub.title()}\n\n"
                "_This index will be populated automatically as concepts are added._\n\n",
                encoding="utf-8",
            )
            print(f"created: {idx}")

    # Git LFS support for assets.
    if not args.no_lfs:
        if ensure_gitattributes(root, LFS_PATTERNS):
            print(f"created: {root / '.gitattributes'}")
        else:
            print(f"up-to-date: {root / '.gitattributes'}")

    print(f"initialized OKF bundle: {root.resolve()}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="OKF note-taking helper")
    sub = parser.add_subparsers(dest="command", required=True)

    new = sub.add_parser("new", help="create a new OKF concept note")
    new.add_argument("path")
    new.add_argument("--title", default=None)
    new.add_argument("--description", default=None)
    new.add_argument("--type", default="Note")
    new.add_argument("--tags", nargs="+", default=None)
    new.set_defaults(func=cmd_new)

    link = sub.add_parser("link", help="add a bundle-relative link between notes")
    link.add_argument("from_path")
    link.add_argument("--to", required=True)
    link.add_argument("--text", default=None)
    link.set_defaults(func=cmd_link)

    idx = sub.add_parser("index", help="generate or update index.md files")
    idx.add_argument("--regenerate", action="store_true")
    idx.set_defaults(func=cmd_index)

    check = sub.add_parser("check", help="check bundle conformance")
    check.set_defaults(func=cmd_check)

    log = sub.add_parser("log", help="append an entry to a log.md")
    log.add_argument("message")
    log.add_argument("--dir", default=None)
    log.add_argument("--date", default=None)
    log.set_defaults(func=cmd_log)

    init = sub.add_parser("init", help="create an empty OKF bundle skeleton")
    init.add_argument("directory", nargs="?", default=".", help="bundle root directory")
    init.add_argument("--name", default=None, help="bundle display name")
    init.add_argument("--no-lfs", action="store_true", help="skip creating .gitattributes for Git LFS")
    init.set_defaults(func=cmd_init)

    lfs = sub.add_parser("lfs-setup", help="create or update .gitattributes for Git LFS")
    lfs.add_argument("directory", nargs="?", default=".", help="bundle root directory")
    lfs.set_defaults(func=cmd_lfs_setup)

    attach = sub.add_parser("attach", help="attach an image to a concept")
    attach.add_argument("concept", help="path to the concept markdown file")
    attach.add_argument("--file", required=True, help="path to the image file")
    attach.add_argument("--caption", default=None, help="image caption / alt text")
    attach.add_argument("--record", action="store_true", help="record asset path in frontmatter")
    attach.set_defaults(func=cmd_attach)

    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
